export function formatSalary(job: JobListing): string {
  const fmt = new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: job.salaryCurrency,
    maximumFractionDigits: 0,
  });
  return `${fmt.format(job.salaryMin)} - ${fmt.format(job.salaryMax)}/${job.salaryPeriod}`;
}

export function getJobBySlug(slug: string): JobListing | undefined {
  return jobListings.find((j) => j.slug === slug);
}

export function getFeaturedJobs(excludeId?: number): JobListing[] {
  return jobListings
    .filter((j) => j.featured && j.id !== excludeId)
    .slice(0, 3);
}

export function getRelatedJobs(
  category: string,
  excludeId: number
): JobListing[] {
  return jobListings
    .filter((j) => j.category === category && j.id !== excludeId)
    .slice(0, 3);
}

export function getRelativeDate(dateString: string): string {
  const now = new Date();
  const posted = new Date(dateString);
  const diffDays = Math.floor(
    (now.getTime() - posted.getTime()) / (1000 * 60 * 60 * 24)
  );
  if (diffDays === 0) return "Today";
  if (diffDays === 1) return "Yesterday";
  if (diffDays < 7) return `${diffDays} days ago`;
  if (diffDays < 30) return `${Math.floor(diffDays / 7)} weeks ago`;
  return `${Math.floor(diffDays / 30)} months ago`;
}
